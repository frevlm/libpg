-- Benchmark schema: 100k seeded accounts and an empty events log.
CREATE TABLE accounts (
  id         bigint PRIMARY KEY,
  balance    numeric(18,6) NOT NULL DEFAULT 0,
  name       text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE events (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  amount     numeric(18,6) NOT NULL,
  at         timestamptz NOT NULL DEFAULT now(),
  note       text
);

INSERT INTO accounts (id, balance, name)
SELECT g, round((random() * 10000)::numeric, 6), 'account-' || g
FROM generate_series(1, 100000) AS g;

VACUUM ANALYZE accounts;

-- Wide list-page table modeled on HHHOJ submissions: 1000 users x 100 rows, deterministic.
CREATE TABLE submissions (
  id          bigint PRIMARY KEY,
  user_id     bigint NOT NULL,
  problem_id  integer NOT NULL,
  submitter   text NOT NULL,
  title       text NOT NULL,
  note        text,
  score       numeric(18,6) NOT NULL,
  submit_time timestamptz NOT NULL,
  accepted    boolean NOT NULL,
  content     jsonb NOT NULL
);

INSERT INTO submissions
SELECT g, (g - 1) % 1000 + 1, g % 500 + 1, 'user-' || ((g - 1) % 1000 + 1), 'Problem ' || (g % 500 + 1) || ': ' || md5(g::text),
       CASE WHEN g % 3 = 0 THEN NULL ELSE 'judged on node ' || (g % 17) END,
       (g % 100000)::numeric / 1000, timestamptz '2024-01-01 00:00:00+00' + g * interval '7 seconds', g % 2 = 0,
       jsonb_build_object('lang', 'cpp17', 'size', g % 65536, 'hash', md5(g::text), 'tags', jsonb_build_array('a', 'b', g % 9),
                          'files', jsonb_build_object('main.cpp', md5((g + 1)::text), 'in', md5((g + 2)::text)))
FROM generate_series(1, 100000) AS g;
CREATE INDEX submissions_user_id ON submissions (user_id, id);

VACUUM ANALYZE submissions;

-- revlm's requests table and its four indexes, inserted in batches.
CREATE TABLE bench_requests (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  time                    timestamptz NOT NULL DEFAULT now(),
  request_id              text,
  response_id             text,
  endpoint                text,
  method                  text,
  user_id                 bigint NOT NULL,
  token_id                bigint NOT NULL,
  input_tokens            int NOT NULL DEFAULT 0,
  output_tokens           int NOT NULL DEFAULT 0,
  cache_read_tokens       int NOT NULL DEFAULT 0,
  cache_creation_1h_tokens int NOT NULL DEFAULT 0,
  cache_creation_5m_tokens int NOT NULL DEFAULT 0,
  tier_multiplier         float8 NOT NULL DEFAULT 1.0,
  service_tier            text,
  channel_multiplier      float8 NOT NULL DEFAULT 1.0,
  channel_id              bigint NOT NULL DEFAULT 0,
  status_code             int NOT NULL DEFAULT 0,
  latency_ms              int NOT NULL DEFAULT 0,
  first_token_latency_ms  int NOT NULL DEFAULT 0,
  error_class             text,
  error_message           text,
  is_stream               boolean NOT NULL DEFAULT false,
  model                   text,
  usd                     numeric(18,6) NOT NULL DEFAULT 0,
  outcome                 text,
  attempts                int NOT NULL DEFAULT 0,
  body_read_us            bigint NOT NULL DEFAULT 0,
  prep_us                 bigint NOT NULL DEFAULT 0,
  upstream_head_us        bigint NOT NULL DEFAULT 0,
  upstream_wait_us        bigint NOT NULL DEFAULT 0,
  relay_us                bigint NOT NULL DEFAULT 0,
  client_write_us         bigint NOT NULL DEFAULT 0,
  request_bytes           bigint NOT NULL DEFAULT 0,
  response_bytes          bigint NOT NULL DEFAULT 0
);
CREATE INDEX bench_requests_user_id_id ON bench_requests (user_id, id);
CREATE INDEX bench_requests_token_id_id ON bench_requests (token_id, id);
CREATE INDEX bench_requests_channel_id_id ON bench_requests (channel_id, id);
CREATE INDEX bench_requests_time ON bench_requests (time);
